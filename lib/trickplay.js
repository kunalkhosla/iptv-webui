// Trick-play thumbnail store: DATA_DIR/trickplay/<mode>-<id>/<t>.jpg, one
// small JPEG per ~interval seconds of the title, where t is the frame's
// time in whole seconds. Coverage can be partial (only the parts a viewer's
// transcode produced, or a full offline pass for Disk-library files, which
// writes a `.complete` marker).

const fs = require("fs");
const path = require("path");

const KEY_RE = /^(movie|series|disk)-\d{1,17}$/;

// Width/height of a baseline or progressive JPEG (SOF0..SOF15 except DHT/JPG/DAC).
function jpegSize(buf) {
  if (!buf || buf.length < 4 || buf[0] !== 0xff || buf[1] !== 0xd8) return null;
  let i = 2;
  while (i + 9 < buf.length) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1];
    if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) { i += 2; continue; }
    const len = buf.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
      return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
    }
    i += 2 + len;
  }
  return null;
}

function createTrickplayStore({ dir, maxBytes = 2 * 1024 ** 3, now = Date.now, touchEveryMs = 3600_000 } = {}) {
  if (!dir) throw new Error("trickplay: dir required");
  fs.mkdirSync(dir, { recursive: true });
  const mem = new Map(); // key -> { times: number[], complete: bool, size: {width,height}|null }

  const keyOf = (mode, id) => `${mode}-${id}`;
  const dirOf = (key) => path.join(dir, key);
  const valid = (key) => KEY_RE.test(key);

  function load(key) {
    let e = mem.get(key);
    if (e) return e;
    const d = dirOf(key);
    const times = [];
    let complete = false;
    let size = null;
    let names = [];
    try { names = fs.readdirSync(d); } catch { names = []; }
    for (const n of names) {
      const m = /^(\d{1,6})\.jpg$/.exec(n);
      if (m) times.push(parseInt(m[1], 10));
      else if (n === ".complete") complete = true;
    }
    times.sort((a, b) => a - b);
    if (times.length) {
      try { size = jpegSize(fs.readFileSync(path.join(d, `${times[0]}.jpg`))); } catch { size = null; }
    }
    e = { times, complete, size };
    if (mem.size > 2000) mem.delete(mem.keys().next().value);
    mem.set(key, e);
    return e;
  }

  function list(mode, id) {
    const key = keyOf(mode, id);
    if (!valid(key)) return { times: [], complete: false, size: null };
    return load(key);
  }

  // Store a finished JPEG (buffer) as frame t. Returns true if written.
  function put(mode, id, t, buf) {
    const key = keyOf(mode, id);
    if (!valid(key) || !Number.isInteger(t) || t < 0 || t > 999999) return false;
    if (!buf || buf.length < 100 || !jpegSize(buf)) return false;
    const e = load(key);
    const d = dirOf(key);
    fs.mkdirSync(d, { recursive: true });
    const tmp = path.join(d, `.${t}.${process.pid}.tmp`);
    fs.writeFileSync(tmp, buf);
    fs.renameSync(tmp, path.join(d, `${t}.jpg`));
    if (!e.times.includes(t)) {
      e.times.push(t);
      e.times.sort((a, b) => a - b);
    }
    if (!e.size) e.size = jpegSize(buf);
    return true;
  }

  function markComplete(mode, id) {
    const key = keyOf(mode, id);
    if (!valid(key)) return;
    const d = dirOf(key);
    fs.mkdirSync(d, { recursive: true });
    fs.writeFileSync(path.join(d, ".complete"), String(now()));
    load(key).complete = true;
  }

  function filePath(mode, id, t) {
    const key = keyOf(mode, id);
    if (!valid(key) || !/^\d{1,6}$/.test(String(t))) return null;
    const f = path.join(dirOf(key), `${parseInt(t, 10)}.jpg`);
    try { if (!fs.statSync(f).isFile()) return null; } catch { return null; }
    // Last use = dir mtime (throttled), for eviction.
    try {
      const st = fs.statSync(dirOf(key));
      if (now() - st.mtimeMs > touchEveryMs) { const d = new Date(now()); fs.utimesSync(dirOf(key), d, d); }
    } catch {}
    return f;
  }

  // Drop least recently used titles until the total size is under maxBytes.
  // Async (stats ~250k files at the cap, must not block the event loop).
  // Titles with a full offline pass (.complete, the Disk library) are never
  // evicted: they would only be regenerated by the next offline pass.
  async function evict() {
    const fsp = fs.promises;
    const titles = [];
    let total = 0;
    let names = [];
    try { names = await fsp.readdir(dir); } catch { names = []; }
    for (const n of names) {
      if (!valid(n)) continue;
      const d = dirOf(n);
      let st;
      try { st = await fsp.stat(d); } catch { continue; }
      if (!st.isDirectory()) continue;
      let files = [];
      try { files = await fsp.readdir(d); } catch {}
      let bytes = 0;
      for (const f of files) { try { bytes += (await fsp.stat(path.join(d, f))).size; } catch {} }
      total += bytes;
      if (files.includes(".complete")) continue;
      titles.push({ key: n, used: st.mtimeMs, bytes });
    }
    titles.sort((a, b) => a.used - b.used);
    let removed = 0;
    for (const t of titles) {
      if (total <= maxBytes) break;
      try { await fsp.rm(dirOf(t.key), { recursive: true, force: true }); } catch { continue; }
      mem.delete(t.key);
      total -= t.bytes;
      removed++;
    }
    return { removed, totalBytes: total, titles: titles.length - removed };
  }

  return { list, put, markComplete, filePath, evict, forget: (mode, id) => mem.delete(keyOf(mode, id)) };
}

module.exports = { createTrickplayStore, jpegSize };
